using Autofac;
using CryptoBook.AI;
using CryptoBook.DTO;
using CryptoBook.Help;
using CryptoBook.Infrastructure;
using CryptoBook.Interfaces;
using CryptoBook.Services;
using CryptoBook.Validation;
using CryptoBook.Views;
using System.IO;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Documents;
using System.Windows.Input;
using System.Windows.Media;

internal static partial class Program
{
    private static async Task ValidateStage11(IsolatedServices isolated, bool input, bool verify, string? evidenceRoot = null)
    {
        var c = isolated.Container;
        var main = Application.Current.Windows.OfType<MainWindow>().Single();
        main.WindowState = WindowState.Normal; main.Width = 1120; main.Height = 780;
        var theme = c.Resolve<IThemeManager>(); theme.ApplyTheme(ApplicationTheme.Light);
        string textPath = Path.Combine(isolated.DemoDirectory, "Focus-example.txt");
        string mdPath = Path.Combine(isolated.DemoDirectory, "Focus-example.md");
        File.WriteAllText(textPath, "ORBIT-731 ordinary fixture.");
        File.WriteAllText(mdPath, "# ORBIT-731 Markdown fixture.");
        Check((await c.Resolve<IWorkspaceFileOpenService>().OpenAsync(mdPath)).Success, "Stage11 Markdown fixture opens.");
        c.Resolve<IMarkdownDocumentState>().Text += "\nUnsent Markdown change.";
        Check((await c.Resolve<IWorkspaceFileOpenService>().OpenAsync(textPath)).Success, "Stage11 ordinary fixture opens.");
        var editor = c.Resolve<IRichTextBoxService>();
        var session = c.Resolve<IDocumentSession>();
        editor.Document.Blocks.Add(new Paragraph(new Run("Unsent ordinary change."))); session.MarkDirty();
        string ordinary = new TextRange(editor.Document.ContentStart, editor.Document.ContentEnd).Text;
        var workspace = (IWorkspaceDocumentSession)session;
        var inactive = workspace.CaptureInactiveDocument();
        var ai = c.Resolve<AiAssistantViewModel>();
        var message = new AiChatMessage("user", "Fictional focus check."); ai.Messages.Add(message); ai.Prompt = "Unsent ORBIT-731";
        var service = c.Resolve<IHelpWindowService>(); service.Open(); await Settle(main);
        var window = Application.Current.Windows.OfType<HelpWindow>().Single();
        var model = (HelpWindowViewModel)window.DataContext;
        var content = c.Resolve<HelpContentService>();
        var viewer = (FlowDocumentScrollViewer)window.FindName("ArticleViewer");
        var scroll = Visuals<ScrollViewer>(viewer).First();
        string evidence = evidenceRoot ?? "docs/help/screenshots/validation/stage11/";
        // Keep later editorial runs separate from the accepted earlier evidence.
        string? evidenceTag = Environment.GetEnvironmentVariable("CRYPTOBOOK_HELP_STAGE11_EVIDENCE_TAG");
        if (!string.IsNullOrEmpty(evidenceTag))
        {
            if (!System.Text.RegularExpressions.Regex.IsMatch(evidenceTag, @"\A[a-zA-Z0-9][a-zA-Z0-9_-]{0,63}\z"))
                throw new ArgumentException("Stage11 evidence tag must be a simple directory name.");
            evidence += evidenceTag + "/";
        }
        var screens = System.Windows.Forms.Screen.AllScreens.Select(s => new { s.Primary, s.Bounds, s.WorkingArea }).ToArray();
        WriteJson(evidence + "environment-" + culture + ".json", new
        {
            culture, commit, screens, dpi = VisualTreeHelper.GetDpi(window),
            renderDpiMeaning = "144/192 are RenderTargetBitmap raster density only; Windows display settings are unchanged."
        });
        if (input)
        {
            model.OpenTopic("doc.create"); await Settle(window);
            var observations = new List<object>();
            window.PreviewKeyUp += (_, e) => observations.Add(new
            {
                key = (e.Key == Key.System ? e.SystemKey : e.Key).ToString(), modifiers = Keyboard.Modifiers.ToString(),
                topic = model.CurrentTopicId, model.Query, model.IsImageOpen,
                focus = Keyboard.FocusedElement?.GetType().Name,
                focusName = (Keyboard.FocusedElement as FrameworkElement)?.Name,
                focusWindow = Keyboard.FocusedElement is DependencyObject focus ? Window.GetWindow(focus)?.GetType().Name : null
            });
            Console.WriteLine("STAGE11_INPUT_READY Close the isolated help window to finish. " + isolated.Root);
            var closed = new TaskCompletionSource(); window.Closed += (_, _) => closed.TrySetResult();
            await closed.Task;
            WriteJson(evidence + "input-" + culture + ".json", new { culture, observations, method = "External input observed by WPF; operator must record whether it was human physical input or OS automation. No routed keys generated by this mode." });
        }
        else
        {
            var rows = new List<object>();
            foreach (var selectedTheme in verify ? new[] { ApplicationTheme.Light } : Enum.GetValues<ApplicationTheme>())
            {
                theme.ApplyTheme(selectedTheme);
                foreach (bool narrow in verify ? new[] { false } : new[] { false, true })
                {
                    window.Width = narrow ? 720 : 1120; window.Height = narrow ? 480 : 780;
                    foreach (var topic in content.GetLocale(culture).Topics)
                    {
                        model.OpenTopic(topic.Id); await Settle(window);
                        Check(model.Status.Length == 0 && viewer.Document.Blocks.Count > 0, $"Rendered {topic.Id}/{selectedTheme}/{narrow}.");
                        var images = content.Find(culture, topic.Id)!.Images;
                        Check(images.All(p => content.LoadImage(culture, content.Find(culture, topic.Id)!, p) is not null), $"Images {topic.Id}/{selectedTheme}/{narrow}.");
                        double overflow = scroll.ExtentWidth - scroll.ViewportWidth;
                        rows.Add(new { topic.Id, theme = selectedTheme.ToString(), narrow, overflow, viewport = scroll.ViewportWidth, height = scroll.ExtentHeight });
                        if (selectedTheme == ApplicationTheme.Light && !narrow)
                            SaveWindow(window, evidence + $"articles/{culture}/{topic.Id}.png");
                        if (topic.Id is "help.use" or "settings.hotkeys" or "md.syntax")
                            SaveWindow(window, evidence + $"layout/{culture}/{selectedTheme}-{(narrow ? "narrow" : "wide")}-{topic.Id}.png");
                        scroll.ScrollToEnd(); await window.Dispatcher.InvokeAsync(window.UpdateLayout);
                        Check(double.IsFinite(scroll.VerticalOffset) && scroll.VerticalOffset <= scroll.ScrollableHeight + 1, $"Scroll bounds {topic.Id}/{selectedTheme}/{narrow}.");
                    }
                }
            }
            theme.ApplyTheme(ApplicationTheme.Light); window.Width = 720; window.Height = 480;
            model.OpenTopic("doc.create"); await Settle(window);
            SaveWindow(window, evidence + $"density/{culture}-144.png", 144);
            SaveWindow(window, evidence + $"density/{culture}-192.png", 192);
            // Exercise every enlarged bitmap; keyboard routing is checked separately with OS input.
            if (!verify || captureFilter != "text")
            foreach (var topic in content.GetLocale(culture).Topics)
            {
                model.OpenTopic(topic.Id); await Settle(window);
                foreach (var button in Visuals<Button>(viewer).Where(b => b.Command == model.ShowImage).ToArray())
                {
                    button.Command!.Execute(button.CommandParameter); await window.Dispatcher.InvokeAsync(window.UpdateLayout);
                    Check(model.IsImageOpen && model.Image!.Source.PixelWidth > 0, $"Enlargement {topic.Id}.");
                    model.CloseImage.Execute(null);
                }
            }
            model.OpenTopic("doc.create"); model.ScrollOffset = 100; model.OpenTopic("doc.save"); model.Back.Execute(null);
            Check(model.CurrentTopicId == "doc.create" && model.ScrollOffset == 100, "History restores the saved reading offset.");
            model.Query = "no-such-ORBIT-731-topic"; model.RunSearch(); Check(model.HasNoResults, "Empty search state.");
            LocalizationManager.SelectCulture(culture == "de-DE" ? "en-US" : "de-DE"); await Settle(window);
            Check(model.Query.Length == 0 && model.Results.Count == 0 && model.CurrentTopicId == "doc.create", "Live language change clears search and retains topic.");
            LocalizationManager.SelectCulture(culture); await Settle(window);
            window.Close(); service.Open(); await Settle(main);
            window = Application.Current.Windows.OfType<HelpWindow>().Single(); model = (HelpWindowViewModel)window.DataContext;
            Check(model.CurrentTopicId == "doc.create" && window.ActualWidth == 720, "Reopening restores topic and narrow geometry.");
            // Enlarge the actual WPF content without changing the user's Windows settings.
            // This exercises constrained layout, but is not an OS DPI transition.
            var root = (FrameworkElement)window.Content;
            viewer = (FlowDocumentScrollViewer)window.FindName("ArticleViewer");
            scroll = Visuals<ScrollViewer>(viewer).First();
            foreach (double scale in new[] { 1.5, 2.0 })
            {
                window.Width = 1440; window.Height = 960;
                root.LayoutTransform = new ScaleTransform(scale, scale); await Settle(window);
                Check(viewer.ActualWidth >= 360 && scroll.ExtentWidth <= scroll.ViewportWidth + 1, $"Scaled WPF content fits at {scale}.");
                var scaled = Capture(window, 96);
                Check(scaled.PixelWidth > 1300 && scaled.PixelHeight > 850, $"Scaled capture includes the transformed client at {scale}.");
                WriteBitmap(scaled, evidence + $"scaled/{culture}-{scale.ToString(System.Globalization.CultureInfo.InvariantCulture)}.png");
            }
            root.LayoutTransform = Transform.Identity;
            WriteJson(evidence + (verify ? "layout-final-" : "layout-") + culture + ".json", new { culture, commit, rows, bindingErrors, checks, scaledLayout = "Root LayoutTransform 1.5/2.0, not Windows DPI" });
            window.Close();
        }
        Check(new TextRange(editor.Document.ContentStart, editor.Document.ContentEnd).Text == ordinary && session.IsDirty, "Both ordinary text and dirty state survive help checks.");
        var after = workspace.CaptureInactiveDocument();
        Check(inactive is not null && after is not null && after.Revision != after.SavedRevision && inactive.Content.SequenceEqual(after.Content), "Inactive dirty Markdown bytes survive help checks.");
        Check(ai.Messages.Contains(message) && ai.Prompt == "Unsent ORBIT-731", "AI message and unsent draft survive help checks.");
    }
}
